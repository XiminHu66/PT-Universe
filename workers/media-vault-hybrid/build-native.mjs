import {readFile,writeFile} from 'node:fs/promises';
const source=await readFile(new URL('../../apps/media-vault/native-download.js',import.meta.url),'utf8');
const generated='// Generated by build-native.mjs; do not edit. No media or credentials.\nexport default '+JSON.stringify(source)+';\n';
const target=new URL('./src/native-download-source.js',import.meta.url);
if(process.argv.includes('--check')){
 if(await readFile(target,'utf8')!==generated)throw Error('Native download module changed: run node build-native.mjs');
}else await writeFile(target,generated);
