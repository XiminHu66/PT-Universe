import {readFile,writeFile} from 'node:fs/promises';
const names=['index.html','app.js','style.css','novels.css','native-download.js','scoped-session.js','account.html','account-app.js','account-session.js','account.css'];
const assets={};for(const name of names)assets[name]=await readFile(new URL('../../apps/media-vault/'+name,import.meta.url),'utf8');
const generated='// Generated by build-preview.mjs from frontend source; do not edit.\nexport default '+JSON.stringify(assets)+';\n';
const target=new URL('./src/preview-assets.js',import.meta.url);
if(process.argv.includes('--check')){if(await readFile(target,'utf8')!==generated)throw Error('Preview assets changed: run node build-preview.mjs');}
else await writeFile(target,generated);
